def qa_piece(name, img, mod, variant=None):
    """Measurements of one finished @1x image against their targets.  Returns the failures."""
    q = post.QA(name, strict=False)
    if name == "Panel":
        q.color("paper field", post.region_mean(img, (30, 30, 98, 98)), "Paper", 3)
        r, c = post.nine_slice_uniformity(img, mod.SPEC["margins"])
        q.max("border row std", r, 2.0)
        q.max("border column std", c, 2.0)
        q.max("field mottling std", float(img[30:98, 30:98, :3].std(axis=(0, 1)).max() * 255), 4.0)
    elif name == "PanelDark":
        q.color("field (strip)", post.region_mean(img, (16, 40, 22, 88)), "Night", 3)
        r, c = post.nine_slice_uniformity(img, mod.SPEC["margins"])
        q.max("border row std", r, 2.0)
        q.max("border column std", c, 2.0)
    elif name.startswith("Button"):
        if variant == "normal":
            q.color("field centre row", post.region_mean(img, (24, 31, 168, 33)), "Lacquer", 4)
        r, c = post.nine_slice_uniformity(img, mod.SPEC["margins"])
        q.max("border row std", r, 2.0)
        q.max("border column std", c, 2.0)
    elif name.startswith("Tab"):
        r, c = post.nine_slice_uniformity(img, mod.SPEC["margins"])
        q.max("border row std", r, 2.0)
        # the inactive tab's straight horizontal grain is a function of y only: the side strips
        # vary along y exactly like the centre does, so Slate scales both identically.  Check
        # that the side columns differ from the centre column by no more than 2 levels (std).
        l, t, rr, b = mod.SPEC["margins"]
        H = img.shape[0]
        centre = img[t:H - b, img.shape[1] // 2, :3] * 255
        side = img[t:H - b, l - 2, :3] * 255
        dev = (side - centre) - (side - centre).mean(0)
        q.max("side vs centre column std", float(dev.std(0).max()), 2.0)
    elif name == "Frame_Portrait":
        win = img[40:220, 40:172, 3]
        q.max("window alpha (centre)", float(win.max()), 0.0)
        q.max("outer ring alpha min", 1.0 - float(min(img[0, 20:-20, 3].min(),
                                                      img[20:-20, 0, 3].min())), 0.05)
    elif name == "Scroll":
        q.color("silk field", post.region_mean(img, (300, 250, 724, 390)), "Paper", 6)
    elif name in ("Title_Logo", "Seal"):
        q.max("outer 2 px ring alpha", post.border_alpha_max(img, 2), 0.02)
    elif name == "Divider":
        q.max("outer 1 px ring alpha", post.border_alpha_max(img, 1), 0.02)
    return [n for n, ok, _ in q.rows if not ok]


def qa_only(pieces):
    """Re-run the QA on the committed @1x art (no rendering)."""
    failures = []
    for spec in pieces:
        name, _, only = spec.partition(":")
        mod = importlib.import_module(name)
        variants = getattr(mod, "VARIANTS", (None,))
        for v in variants:
            fname = mod.FILE[v] if hasattr(mod, "FILE") else mod.NAME
            img = post.load(os.path.join(common.ART_UI, fname + ".png"))
            post.save_asset(img, "Art/UI/%s.png" % fname, check_only=True)
            failures += ["%s: %s" % (fname, f) for f in qa_piece(fname, img, mod, v)]
    if failures:
        print("[ui_chrome] QA FAILED:\n  " + "\n  ".join(failures))
        sys.exit(1)
    print("[ui_chrome] QA ok (%d pieces)" % len(pieces))


def write_nineslice():
    p1 = os.path.join(common.ART_UI, "NineSlice.json")
    js = dict(NOTES)
    js.update(NINE)
    os.makedirs(common.ART_UI, exist_ok=True)
    with open(p1, "w", encoding="utf-8") as f:
        json.dump(js, f, indent=2, ensure_ascii=False)
        f.write("\n")
    two = {"_about": "9-slice margins of the @2x masters (twice NineSlice.json)."}
    for k, v in NINE.items():
        two[k.replace(".png", "@2x.png")] = (v * 2 if isinstance(v, int) else [x * 2 for x in v])
    p2 = os.path.join(common.SRC_UI, "NineSlice@2x.json")
    os.makedirs(common.SRC_UI, exist_ok=True)
    with open(p2, "w", encoding="utf-8") as f:
        json.dump(two, f, indent=2)
        f.write("\n")
    return p1, p2


def update_manifest(paths):
    """Read-modify-write ArtSource/manifest.json under an exclusive lock (other artists add their
    files concurrently): add our files, keep everyone else's, bump the version."""
    import fcntl
    import tempfile
    art = os.path.join(REPO_DIR, "ArtSource")
    os.makedirs(art, exist_ok=True)
    mpath = os.path.join(art, "manifest.json")
    rel = sorted(os.path.relpath(p, art).replace(os.sep, "/") for p in paths)
    with open(os.path.join(tempfile.gettempdir(), "ironreign_artsource_manifest.lock"), "w") as lk:
        fcntl.flock(lk, fcntl.LOCK_EX)
        data = {"version": 0, "files": []}
        if os.path.exists(mpath):
            with open(mpath, encoding="utf-8-sig") as f:
                data = json.load(f)
        files = data.setdefault("files", [])
        dict_style = any(isinstance(e, dict) for e in files)
        have = {(e.get("path") if isinstance(e, dict) else e) for e in files}
        added = 0
        for r in rel:
            if r in have:
                continue
            files.append({"path": r, "family": "ui_chrome"} if dict_style else r)
            added += 1
        data["version"] = int(data.get("version", 0)) + 1
        tmp = mpath + ".tmp.%d" % os.getpid()
        with open(tmp, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2, ensure_ascii=False)
            f.write("\n")
        os.replace(tmp, mpath)
        fcntl.flock(lk, fcntl.LOCK_UN)
    print("[ui_chrome] manifest version %d (+%d files)" % (data["version"], added))
    return data["version"]


def main():
    try:
        from ironart import scene                    # inside Blender (render.sh)
        args = scene.args()
    except ImportError:                              # system python3: --qa-only
        args = sys.argv[1:]
    preview = "--preview" in args
    pieces = [a for a in args if not a.startswith("--")] or ORDER
    if "--qa-only" in args:
        return qa_only(pieces)
    times = {}
    written = []
    failures = []
    t0 = time.time()
    for spec in pieces:
        name, _, only = spec.partition(":")          # e.g. button:hover,disabled
        mod = importlib.import_module(name)
        variants = getattr(mod, "VARIANTS", (None,))
        if only:
            variants = [v for v in variants if v in only.split(",")]
        for v in variants:
            res = common.render_piece(mod, v, preview=preview)
            fname = mod.FILE[v] if hasattr(mod, "FILE") else mod.NAME
            times[fname] = res["times"]
            if not preview:
                failures += ["%s: %s" % (fname, f) for f in qa_piece(fname, res["img1"], mod, v)]
                p1, p2 = common.save_pair(res, fname)
                written += [p1, p2]
            else:
                out = common.out_dir("preview")
                post.save(res["img1"], os.path.join(out, fname + ".png"))
                post.save(res["img2"], os.path.join(out, fname + "@2x.png"))
    if not preview:
        n1, n2 = write_nineslice()
        written += [n1, n2]
        src = [p for p in written if os.path.abspath(p).startswith(os.path.join(REPO_DIR, "ArtSource"))]
        update_manifest(src)
        if "--no-previews" not in args:
            import preview as pv
            pv.main(common.out_dir())
    times["_total_s"] = round(time.time() - t0, 1)
    with open(os.path.join(common.out_dir(), "timings.json"), "w") as f:
        json.dump(times, f, indent=2)
    print("[ironart] TIMES", json.dumps(times))
    for p in written:
        print("[ui_chrome] wrote", os.path.relpath(p, REPO_DIR))
    if failures:
        print("[ui_chrome] QA FAILED:\n  " + "\n  ".join(failures))
        sys.exit(1)
    print("[ui_chrome] QA ok")


if __name__ == "__main__":
    main()
