"""UI chrome family: regenerate every UI chrome asset deterministically.

    Tools/BlenderArt/render.sh Tools/BlenderArt/ui_chrome/build.py [piece ...] [--preview]
                                                                   [--no-previews]

Pieces (default: all): panel panel_dark button tab frame_portrait divider seal scroll logo

Outputs
    Content/Data/Art/UI/{Panel,PanelDark,Button,Button_Hover,Button_Pressed,Button_Disabled,
                         Tab,Tab_Active,Frame_Portrait,Divider,Seal,Scroll,Title_Logo}.png  (@1x)
    Content/Data/Art/UI/NineSlice.json                          9-slice margins (read by the UI)
    ArtSource/UI/<name>@2x.png + NineSlice@2x.json              2x masters (same render)
    ArtSource/manifest.json                                     the @2x files are listed (+version)
    $IRONART_OUT/ui_chrome/                                     raw renders, previews, timings

Every piece is rendered once at 4x its @1x size (1 px = 1 mm, Cycles CPU, no denoiser) and
Lanczos-downsampled to @2x and @1x.  QA (asserted): manifest contract, field colours on their
tokens, 9-slice border strips uniform along the stretch, empty portrait window, clear borders.
"""

